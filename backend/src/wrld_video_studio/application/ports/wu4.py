from __future__ import annotations

from collections.abc import Callable
from pathlib import Path
from typing import Any, Protocol


class SecureProjectFilePort(Protocol):
    size: int
    def read(self, amount: int = -1) -> bytes: ...
    def seek(self, offset: int) -> None: ...
    def sha256(self) -> str: ...
    def close(self) -> None: ...
    def __enter__(self) -> SecureProjectFilePort: ...
    def __exit__(self, exc_type: object, exc: object, traceback: object) -> None: ...


class ProjectResolverPort(Protocol):
    def roots(self) -> tuple[dict[str, str], ...]: ...
    def directories(self, root_id: str, parent: str = "") -> tuple[dict[str, str], ...]: ...
    def resolve_directory(self, root_id: str, relative_path: str) -> Path: ...
    def open_project_file(self, project_root: Path, relative_path: str) -> SecureProjectFilePort: ...
    def resolve_project_file(self, project_root: Path, relative_path: str) -> Path: ...


class ProjectCatalogStorePort(Protocol):
    def read(self) -> dict[str, Any]: ...
    def mutate(self, operation: Callable[[dict[str, Any]], None]) -> dict[str, Any]: ...


class ProjectLoaderPort(Protocol):
    def load(self, album_project: str | Path) -> Any: ...


class EditorStateStorePort(Protocol):
    def read(self, project_id: str) -> dict[str, Any]: ...
    def create(self, project_id: str, document: dict[str, Any]) -> dict[str, Any]: ...
    def update(self, project_id: str, expected_revision: int, document: dict[str, Any]) -> dict[str, Any]: ...


class ProjectDocumentStorePort(Protocol):
    def read(self, project_id: str) -> dict[str, Any]: ...
    def create(self, project_id: str, document: dict[str, Any]) -> dict[str, Any]: ...
    def update(self, project_id: str, expected_revision: int, document: dict[str, Any]) -> dict[str, Any]: ...


__all__ = ["EditorStateStorePort", "ProjectCatalogStorePort", "ProjectDocumentStorePort", "ProjectLoaderPort", "ProjectResolverPort", "SecureProjectFilePort"]
