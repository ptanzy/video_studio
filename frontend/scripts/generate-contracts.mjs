import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { compileFromFile } from 'json-schema-to-typescript'

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schemaRoot = resolve(frontendRoot, '..', 'contracts', 'schemas')
const outputRoot = resolve(frontendRoot, 'src', 'api', 'generated')
const contracts = [
  ['project-catalog-v2.schema.json', 'project-catalog-v2.ts'],
  ['project-inventory-v1.schema.json', 'project-inventory-v1.ts'],
  ['project-scan-v1.schema.json', 'project-scan-v1.ts'],
  ['import-handoff-v1.schema.json', 'import-handoff-v1.ts'],
  ['project-preferences-v1.schema.json', 'project-preferences-v1.ts'],
  ['import-handoff-v2.schema.json', 'import-handoff-v2.ts'],
  ['creation-state-v1.schema.json', 'creation-state-v1.ts'],
  ['creation-state-v2.schema.json', 'creation-state-v2.ts'],
  ['creation-state-v3.schema.json', 'creation-state-v3.ts'],
  ['creation-state-v4.schema.json', 'creation-state-v4.ts'],
  ['youtube-metadata-editor-v1.schema.json', 'youtube-metadata-editor-v1.ts'],
  ['youtube-metadata-v1.schema.json', 'youtube-metadata-v1.ts'],
]
const options = {
  bannerComment: '/* Generated by npm run contracts:generate. Do not edit. */',
  style: { singleQuote: true, semi: false, trailingComma: 'all' },
  unknownAny: false,
}

const generateInto = async (directory) => {
  await mkdir(directory, { recursive: true })
  for (const [schema, output] of contracts) {
    const source = await compileFromFile(join(schemaRoot, schema), options)
    await writeFile(join(directory, output), source, 'utf8')
  }
}

if (process.argv.includes('--check')) {
  const temporary = await mkdtemp(join(tmpdir(), 'wrld-contracts-'))
  try {
    await generateInto(temporary)
    const mismatches = []
    for (const [, output] of contracts) {
      const [expected, actual] = await Promise.all([
        readFile(join(temporary, output), 'utf8'),
        readFile(join(outputRoot, output), 'utf8').catch(() => ''),
      ])
      if (expected !== actual) mismatches.push(output)
    }
    if (mismatches.length) {
      throw new Error(`Generated contracts are stale: ${mismatches.join(', ')}`)
    }
  } finally {
    await rm(temporary, { recursive: true, force: true })
  }
} else {
  await generateInto(outputRoot)
}
